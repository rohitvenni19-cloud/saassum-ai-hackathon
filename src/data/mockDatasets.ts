// Generate 84 full records deterministically for full realism
export function generateFull84Records(): CustomerRecord[] {
  const records = [...INITIAL_RAW_CUSTOMERS];
  const cities = ['Hyderabad', 'HYD', 'Hyd', 'Secunderabad', 'Bengaluru', 'BLR', 'Mumbai', 'Delhi', 'Chennai'];
  const tiers: ('Free' | 'Pro' | 'Enterprise')[] = ['Free', 'Pro', 'Enterprise'];
  const firstNames = ['Aarav', 'Neha', 'Kabir', 'Aditi', 'Suresh', 'Pooja', 'Rahul', 'Sunita', 'Gaurav', 'Kavita', 'Manish', 'Ritu'];
  const lastNames = ['Gupta', 'Patel', 'Nair', 'Singh', 'Chawla', 'Bansal', 'Chatterjee', 'Reddy', 'Mehta', 'Iyer'];

  for (let i = records.length + 1; i <= 84; i++) {
    const padId = String(i).padStart(3, '0');
    const fName = firstNames[i % firstNames.length];
    const lName = lastNames[i % lastNames.length];
    const isMessyCasing = i % 7 === 0;
    const isWhitespace = i % 5 === 0;
    const isMessyEmail = i % 4 === 0;
    const isNullPhone = i % 11 === 0;
    const isMessyDate = i % 3 === 0;
    const isMessyCity = i % 6 === 0;
    const isNullRev = i % 13 === 0;

    const rawName = isWhitespace ? `  ${fName} ${lName} ` : isMessyCasing ? `${fName.toUpperCase()} ${lName.toLowerCase()}` : `${fName} ${lName}`;
    const rawEmail = isMessyEmail ? `${fName}.${lName}@CORP.IN`.toUpperCase() : `${fName.toLowerCase()}.${lName.toLowerCase()}@acme.co`;
    const rawCity = isMessyCity ? (i % 2 === 0 ? 'HYD' : 'BLR') : cities[i % cities.length];
    const rawDate = isMessyDate ? `${(i % 12) + 1}/15/2023` : `2023-${String((i % 12) + 1).padStart(2, '0')}-15`;

    records.push({
      id: padId,
      customer_id: i === 42 ? 'CUST-1049' : `CUST-${1040 + i}`,
      full_name: rawName,
      email: rawEmail,
      phone_number: isNullPhone ? '' : `+91 98${i}${i}0123`,
      signup_date: rawDate,
      city: rawCity,
      account_tier: tiers[i % tiers.length],
      annual_revenue: isNullRev ? null : (i * 2400) % 180000,
      has_duplicate_id: i === 42,
      has_whitespace_name: isWhitespace,
      has_uppercase_email: isMessyEmail,
      has_unnormalized_phone: !isNullPhone && i % 2 === 0,
      has_unparsed_date: isMessyDate,
      has_unnormalized_city: isMessyCity,
      has_missing_revenue: isNullRev,
    });
  }
  return records;
}

